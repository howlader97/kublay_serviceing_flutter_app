  static String? localTrans(String text, String lang) {
    try {
      if (text.trim().isEmpty) return text;
      String targetLang = lang.split('_')[0].toLowerCase();

      if (targetLang == "en") return text;

      final normalized = text.trim().toLowerCase();
      final withSpaces = normalized.replaceAll('_', ' ');

      final override = _manualOverrides[targetLang]?[normalized] ??
          _manualOverrides[targetLang]?[withSpaces] ??
          _manualOverrides[targetLang]?[text.trim()];
      if (override != null) return override;
    } catch (e) {
      errorLog("localTrans", e);
    }
    return null;
  }

  static Future<String> translate(String text, String lang) async {
    try {
      if (text.trim().isEmpty) return text;
      String targetLang = lang.split('_')[0].toLowerCase();

      // If English, return original
      if (targetLang == "en") return text;

      // Check manual overrides first for UI specific translations
      final normalized = text.trim().toLowerCase();
      final withSpaces = normalized.replaceAll('_', ' ');

      final override = _manualOverrides[targetLang]?[normalized] ??
          _manualOverrides[targetLang]?[withSpaces] ??
          _manualOverrides[targetLang]?[text.trim()];
      if (override != null) return override;

      final cacheKey = "tr_${text}_$targetLang";
      final cached = await TranslationCache.get(cacheKey);

      if (cached != null && cached.isNotEmpty) return cached;

      var translated = await _translator.translate(text, to: targetLang);

      await TranslationCache.set(cacheKey, translated.text);
      return translated.text;
    } catch (e) {
      return text;
    }
  }
